"""Esquemas de POST /api/v1/ai/suggest-service (description + example en ingles)."""

from marshmallow import Schema, fields, pre_load, validate

from services.prompts import DEFAULT_TECHNIQUE, TECHNIQUES


class SuggestServiceRequestSchema(Schema):
    description = fields.String(required=True, validate=validate.Length(min=10, max=1000), metadata={
        'description': 'Free-text description of the vehicle problem, as the customer would say it (10-1000 chars).',
        'example': 'El carro vibra cuando freno en bajada'})
    technique = fields.String(load_default=DEFAULT_TECHNIQUE, validate=validate.OneOf(TECHNIQUES), metadata={
        'description': 'Prompting technique: zero_shot, few_shot (default) or cot (chain-of-thought).',
        'example': 'few_shot'})

    @pre_load
    def strip_description(self, data, **kwargs):
        if isinstance(data, dict) and isinstance(data.get('description'), str):
            data = {**data, 'description': data['description'].strip()}
        return data


class SuggestionSchema(Schema):
    service_id = fields.Integer(metadata={'description': 'Catalog id of the suggested service.', 'example': 4})
    service_name = fields.String(metadata={
        'description': 'Service name, read from the database.', 'example': 'Rectificación de discos de freno'})
    base_price = fields.Integer(metadata={
        'description': 'Base price in COP, read from the database (never generated by the model).',
        'example': 220000})
    estimated_duration_minutes = fields.Integer(metadata={
        'description': 'Estimated duration in minutes, read from the database.', 'example': 120})
    confidence = fields.String(metadata={
        'description': "Model confidence: 'high', 'medium' or 'low'.", 'example': 'high'})
    reason = fields.String(metadata={
        'description': 'Short justification written by the model in the language of the customer.',
        'example': 'La vibracion al frenar suele indicar discos alabeados.'})


class RetrievalSchema(Schema):
    strategy = fields.String(metadata={
        'description': 'Retrieval strategy used to build the context (keyword matching).', 'example': 'keyword'})
    fallback_full_catalog = fields.Boolean(metadata={
        'description': 'True when no keyword matched and the whole active catalog was sent as context.',
        'example': False})
    candidate_service_ids = fields.List(fields.Integer(), metadata={
        'description': 'Services injected into the prompt as context, best match first.', 'example': [4, 3, 2]})


class UsageSchema(Schema):
    input_tokens = fields.Integer(metadata={'description': 'Prompt tokens billed as input.', 'example': 412})
    output_tokens = fields.Integer(metadata={'description': 'Answer tokens billed as output.', 'example': 96})
    thinking_tokens = fields.Integer(metadata={
        'description': 'Internal reasoning tokens (billed as output by Gemini); 0 if the model did not think.',
        'example': 0})
    latency_ms = fields.Integer(metadata={
        'description': 'End-to-end time of the provider call in milliseconds, retries included.', 'example': 1180})
    attempts = fields.Integer(metadata={
        'description': 'Number of attempts (more than 1 when a 429/503 was retried).', 'example': 1})


class SuggestServiceResponseSchema(Schema):
    ai_call_id = fields.Integer(metadata={'description': 'Id of the row stored in the ai_calls log.', 'example': 17})
    technique = fields.String(metadata={'description': 'Prompting technique used.', 'example': 'few_shot'})
    model = fields.String(metadata={'description': 'Model version that answered.', 'example': 'gemini-3.5-flash-lite'})
    suggestions = fields.List(fields.Nested(SuggestionSchema), metadata={
        'description': 'Up to 3 suggested services, most likely first. Empty if nothing in the catalog fits.',
        'example': [{'service_id': 4, 'service_name': 'Rectificación de discos de freno', 'base_price': 220000,
                     'estimated_duration_minutes': 120, 'confidence': 'high',
                     'reason': 'La vibracion al frenar suele indicar discos alabeados.'}]})
    notes = fields.String(metadata={
        'description': 'Extra advice from the model, e.g. safety warnings. May be empty.',
        'example': 'Los frenos son un tema de seguridad; agenda pronto.'})
    reasoning = fields.String(allow_none=True, metadata={
        'description': 'Step-by-step analysis written by the model; only filled with technique=cot, otherwise null.',
        'example': '1) Sistema de frenos. 2) Discos alabeados por calor. 3) Rectificacion de discos.'})
    discarded_service_ids = fields.List(fields.Raw(), metadata={
        'description': 'Ids the model proposed that were NOT in the context (hallucinations), removed by the API.',
        'example': []})
    retrieval = fields.Nested(RetrievalSchema, metadata={
        'description': 'How the catalog context was retrieved (RAG).', 'example': {
            'strategy': 'keyword', 'fallback_full_catalog': False, 'candidate_service_ids': [4, 3, 2]}})
    usage = fields.Nested(UsageSchema, metadata={
        'description': 'Token usage and latency of the call.', 'example': {
            'input_tokens': 412, 'output_tokens': 96, 'thinking_tokens': 0, 'latency_ms': 1180, 'attempts': 1}})
